const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { localContext } = require('../src/cli')

test('local review captures staged and unstaged changes and excludes secret filenames', () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'pulse-test-'))
  const git = args => execFileSync('git', ['-C', directory, ...args], { stdio: 'pipe' })
  try {
    git(['init'])
    fs.writeFileSync(path.join(directory, 'PRODUCT_INTENT.md'), 'Keep it simple')
    fs.writeFileSync(path.join(directory, 'a.js'), 'const a = 1\n')
    fs.writeFileSync(path.join(directory, 'b.js'), 'const b = 1\n')
    fs.writeFileSync(path.join(directory, '.env'), 'SECRET=old\n')
    git(['add', '.'])
    git(['-c', 'user.name=Pulse Test', '-c', 'user.email=test@example.invalid', 'commit', '-m', 'fixture'])
    fs.writeFileSync(path.join(directory, 'a.js'), 'const a = 2\n')
    git(['add', 'a.js'])
    fs.writeFileSync(path.join(directory, 'b.js'), 'const b = 3\n')
    fs.writeFileSync(path.join(directory, '.env'), 'SECRET=new\n')
    fs.writeFileSync(path.join(directory, 'untracked.js'), 'not included')
    const context = localContext(directory)
    assert.deepEqual(context.files.map(f => f.filename), ['a.js', 'b.js'])
    assert.equal(context.incomplete, true)
    assert.equal(context.intent, 'Keep it simple')
    assert.doesNotMatch(JSON.stringify(context), /SECRET=new/)
  } finally { fs.rmSync(directory, { recursive: true, force: true }) }
})
